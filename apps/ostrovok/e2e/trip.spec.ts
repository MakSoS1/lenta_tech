import { test, expect } from '@playwright/test';
test('creates, compares, edits, quotes, confirms and restores the same server order', async ({ page }, testInfo) => {
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Поездка, которая складывается.'})).toBeVisible();
 await expect(page.getByLabel('Ваш запрос')).toBeVisible();
 await page.screenshot({path:testInfo.outputPath(`landing-${testInfo.project.name}.png`),fullPage:true});
 await page.getByLabel('Ваш запрос').fill('Из Москвы в Сочи 15 ноября 2026 на 5 ночей, двое взрослых, бюджет 180000 рублей');
 await page.getByRole('button',{name:'Собрать поездку',exact:true}).click();
 await expect(page.getByTestId('trip-version')).toBeVisible();
 await page.getByLabel('Откуда',{exact:true}).selectOption('moscow');
 await page.getByLabel('Куда',{exact:true}).selectOption('sochi');
 await page.getByLabel('Дата отправления').fill('2026-11-15');
 await page.getByLabel('Ночей').fill('5');
 await page.getByLabel('Взрослых').fill('2');
 await page.getByLabel('Бюджет, ₽').fill('180000');
 await page.getByRole('button',{name:'Применить условия'}).click();
 await expect(page.getByTestId('plan-card').first()).toBeVisible();
 await expect(page.getByRole('button',{name:'Применить условия'})).toBeEnabled();
 await page.screenshot({path:testInfo.outputPath(`comparison-${testInfo.project.name}.png`),fullPage:true});
 await page.getByRole('region',{name:'Есть куда отправиться'}).screenshot({path:testInfo.outputPath(`comparison-cards-${testInfo.project.name}.png`)});
 await page.getByTestId('plan-card').first().getByRole('button',{name:/Выбрать поездку|Выбрано/}).click();
 await expect(page.getByRole('heading',{name:'Всё по порядку'})).toBeVisible();
 await page.getByLabel('Ночей').fill('6');
 await page.getByRole('button',{name:'Применить условия'}).click();
 await expect(page.getByRole('heading',{name:'Что изменилось'})).toBeVisible();
 await page.getByTestId('plan-card').first().getByRole('button',{name:/Выбрать поездку|Выбрано/}).click();
 await page.getByRole('button',{name:'Проверить итоговую цену'}).click();
 const confirm = page.getByRole('button',{name:'Подтвердить демозаказ'});
 await expect(confirm).toBeDisabled();
 await page.getByLabel('Я подтверждаю состав поездки и демонстрационную сумму').check();
 await expect(confirm).toBeEnabled();
 await confirm.click();
 await expect(page.getByRole('heading',{name:'Поездка собрана!'})).toBeVisible();
 const orderId = await page.getByTestId('order-id').innerText();
 await page.reload();
 await expect(page.getByTestId('order-id')).toHaveText(orderId);
 await expect(page.getByRole('button',{name:'Запомнить',exact:true})).toBeDisabled();
 await page.getByLabel('Сохранить эти предпочтения').check();
 await page.getByRole('button',{name:'Запомнить',exact:true}).click();
 await expect(page.getByText('Питание, возврат и расположение сохранены с вашего согласия.')).toBeVisible();
 await page.getByRole('button',{name:'Удалить сохранённое'}).click();
 await expect(page.getByText('Сохранённые предпочтения удалены.')).toBeVisible();
 await page.getByRole('button',{name:'Запросить раннее заселение'}).click();
 await expect(page.getByRole('button',{name:'Запрос отправлен'})).toBeDisabled();
 await page.getByRole('button',{name:'Мои поездки'}).click();
 await page.locator('.history-item').first().click();
 await expect(page.getByTestId('order-id')).toHaveText(orderId);
 await expect(page.getByText('Бронирование и оплата имитируются',{exact:true}).first()).toBeVisible();
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
 await page.screenshot({path:testInfo.outputPath(`receipt-${testInfo.project.name}.png`),fullPage:true});
 await page.locator('.checkout').screenshot({path:testInfo.outputPath(`receipt-card-${testInfo.project.name}.png`)});
});
